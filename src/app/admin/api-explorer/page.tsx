import { DashCard, DashboardHeader, DashboardShell } from '@/components/admin/dashboard'
import { BentoCard, BentoGrid } from '@/components/admin/grid'
import type { AdminHeroKpi } from '@/components/admin/hero-kpi'
import { Badge } from '@/components/catalyst/badge'
import { TableBody, TableCell, TableHead, TableHeader, TableRow } from '@/components/catalyst/table'
import { Text } from '@/components/catalyst/text'
import { ChartFrame, HearstDonutChart, type DonutSlice } from '@/components/charts'
import { AdminTable, tableCol } from '@/components/compositions'
import { requireSession } from '@/lib/auth'
import { BACKEND_ENDPOINTS, pathParamNames, type BackendEndpoint, type EndpointAuth } from '@/lib/backend/endpoints'
import { backendUrl } from '@/lib/env'
import { formatNumber } from '@/lib/format'
import { editorial, isAvailable } from '@/lib/vaults/model'
import {
  BoltIcon,
  BookOpenIcon,
  CpuChipIcon,
  QueueListIcon,
} from '@heroicons/react/16/solid'
import type { Metadata } from 'next'
import { ExplorerRow } from './explorer-row'

export const metadata: Metadata = { title: 'API explorer' }
export const dynamic = 'force-dynamic'

type ExplorerGroup = {
  id: string
  title: string
  description: string
  filter: (endpoint: BackendEndpoint) => boolean
}

const GROUPS: readonly ExplorerGroup[] = [
  {
    id: 'safe-reads',
    title: 'Safe reads',
    description: 'Business GETs and health probes — calling one has no side effect.',
    filter: (e) => e.method === 'GET' && e.category !== 'ai-context',
  },
  {
    id: 'ai-context',
    title: 'AI context',
    description: 'Generated by the backend — never a primary business fact.',
    filter: (e) => e.category === 'ai-context',
  },
  {
    id: 'actions',
    title: 'Side-effect actions',
    description:
      'Keeper POSTs, financial and administrative. Listed here for reference; they run from Keeper Actions, each requiring explicit confirmation.',
    filter: (e) => e.category === 'keeper',
  },
  {
    id: 'operational',
    title: 'Operational POSTs',
    description:
      'Non-keeper writes: authentication, indexer trigger, account creation. Each runs from its own surface (login, Service, client simulator).',
    filter: (e) => e.method === 'POST' && e.category !== 'keeper',
  },
]

const AUTH_LEVELS: readonly { auth: EndpointAuth; label: string; detail: string }[] = [
  { auth: 'public', label: 'Public', detail: 'Neither session nor token is required.' },
  { auth: 'session', label: 'Session', detail: 'A signed-in investor or administrator.' },
  { auth: 'admin', label: 'Administrator', detail: 'A session whose backend role is admin.' },
]

// Registry breakdown by category: every endpoint genuinely carries this field
// (grouping a per-row datum, not an invented counter), and the total is real
// (= number of endpoints in the registry).
const CATEGORY_LABELS: Record<BackendEndpoint['category'], string> = {
  probe: 'Probes',
  business: 'Business',
  'ai-context': 'AI context',
  keeper: 'Keeper actions',
}

function countBy(filter: (e: BackendEndpoint) => boolean): number {
  return BACKEND_ENDPOINTS.filter(filter).length
}

function curlFor(method: string, path: string, auth: string): string {
  const base = backendUrl() ?? '$HEARST_API_URL'
  const lines = [
    `curl -X ${method} '${base}${path}'`,
    `  -H 'Accept: application/json'`,
    `  -H 'X-Request-Id: <uuid>'`,
  ]
  if (auth !== 'public') lines.push(`  -H 'Authorization: Bearer <REDACTED>'`)
  return lines.join(' \\\n')
}

/**
 * API explorer — cockpit shape: compact command bar, then explicit bento rows.
 * BACKEND_ENDPOINTS registry, live probes via ExplorerRow.
 */
export default async function ApiExplorerPage() {
  await requireSession()

  const safeReadsCount = countBy((e) => e.method === 'GET' && e.category !== 'ai-context')
  const aiContextCount = countBy((e) => e.category === 'ai-context')
  const actionsCount = countBy((e) => e.category === 'keeper')

  // Parts of a whole: endpoints grouped by their real category.
  const byCategory = new Map<BackendEndpoint['category'], number>()
  for (const endpoint of BACKEND_ENDPOINTS) {
    const seen = byCategory.get(endpoint.category)
    byCategory.set(endpoint.category, seen === undefined ? 1 : seen + 1)
  }
  const categorySlices: readonly DonutSlice[] = [...byCategory.entries()]
    .map(([category, value]) => ({ label: CATEGORY_LABELS[category], value }))
    .sort((a, b) => b.value - a.value)

  const kpis: readonly AdminHeroKpi[] = [
    {
      id: 'total',
      title: 'Total endpoints',
      value: editorial(formatNumber(BACKEND_ENDPOINTS.length)),
      icon: QueueListIcon,
    },
    {
      id: 'safe-reads',
      title: 'Safe reads',
      value: editorial(formatNumber(safeReadsCount)),
      icon: BookOpenIcon,
    },
    {
      id: 'actions',
      title: 'Actions',
      value: editorial(formatNumber(actionsCount)),
      icon: BoltIcon,
    },
    {
      id: 'ai-context',
      title: 'AI context',
      value: editorial(formatNumber(aiContextCount)),
      icon: CpuChipIcon,
    },
  ]

  return (
    <DashboardShell>
      <DashboardHeader
        title="API explorer"
        description="BACKEND_ENDPOINTS registry — safe reads, actions, and AI context."
        kpis={kpis}
      />

      {/* Row A — the registry split beside the two reading notes, stacked so
          the right column ends on the chart's line. */}
      <BentoGrid>
        <BentoCard span={6}>
          <ChartFrame
            question="How is the registry split by action type?"
            unit="number of endpoints, by category"
            state={{ type: 'plotted' }}
          >
            <HearstDonutChart slices={categorySlices} unit="endpoints" />
          </ChartFrame>
        </BentoCard>
        <BentoCard span={6}>
          <div className="flex min-w-0 flex-col gap-6">
            <DashCard title="What a row lets you do" titleLevel={2}>
              <Text>
                A safe read can be called directly from its row. The response arrives with its HTTP status,
                its duration and request id, and it is shown exactly as the backend returned it — nothing is
                cached, rounded, or rewritten on return.
              </Text>
              <Text className="mt-4">
                Two row types carry no button, and say so rather than offering one that could never
                succeed: a POST, which belongs to Keeper Actions and its confirmation step, and a path containing a{' '}
                <span className="font-mono">:parameter</span>, whose legitimate value comes from an earlier response
                rather than a text field.
              </Text>
            </DashCard>
            <DashCard title="Path parameters" titleLevel={2}>
              <Text>
                Rows with <span className="font-mono">:param</span> are documented but not directly callable —
                the legitimate value comes from an earlier backend response.
              </Text>
            </DashCard>
          </div>
        </BentoCard>
      </BentoGrid>

      {/* Row B — access levels: one thin table band. */}
      <BentoGrid>
        <BentoCard span={12}>
          <DashCard
            title="Authorization"
            subtitle="Registry access levels, with the endpoint count at each."
            titleLevel={2}
          >
            <AdminTable className="[&_table]:min-w-[40rem]">
              <TableHead>
                <TableRow>
                  <TableHeader className={tableCol.status}>Level</TableHeader>
                  <TableHeader className={tableCol.numeric}>Endpoints</TableHeader>
                  <TableHeader className={tableCol.primary}>What it requires</TableHeader>
                </TableRow>
              </TableHead>
              <TableBody>
                {AUTH_LEVELS.map((level) => (
                  <TableRow key={level.auth}>
                    <TableCell className={`${tableCol.status} font-medium`}>{level.label}</TableCell>
                    <TableCell className={tableCol.numeric}>
                      {formatNumber(countBy((e) => e.auth === level.auth))}
                    </TableCell>
                    <TableCell className={tableCol.primary}>{level.detail}</TableCell>
                  </TableRow>
                ))}
              </TableBody>
            </AdminTable>
          </DashCard>
        </BentoCard>
      </BentoGrid>

      {/* Rows C — registry groups: one full-width card per group, the count
          badge on the title row. */}
      {GROUPS.map((group) => {
        const endpoints = BACKEND_ENDPOINTS.filter(group.filter)
        if (endpoints.length === 0) return null

        return (
          <BentoGrid key={group.id}>
            <BentoCard span={12}>
              <DashCard
                title={group.title}
                subtitle={group.description}
                titleLevel={2}
                action={<Badge color="neutral">{formatNumber(endpoints.length)}</Badge>}
              >
                {endpoints.map((endpoint) => (
                  <ExplorerRow
                    key={endpoint.id}
                    endpoint={endpoint}
                    curl={curlFor(endpoint.method, endpoint.path, endpoint.auth)}
                    pathParams={pathParamNames(endpoint.path)}
                  />
                ))}
              </DashCard>
            </BentoCard>
          </BentoGrid>
        )
      })}
    </DashboardShell>
  )
}
